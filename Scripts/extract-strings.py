#!/usr/bin/env python3
"""Collects Dockside's user-facing strings and keeps the .lproj/Localizable.strings files in sync.

    python3 Scripts/extract-strings.py          # update every language, report untranslated keys
    python3 Scripts/extract-strings.py --check  # exit 1 if any language is missing keys (for CI)

English (en.lproj) is regenerated from the source. Other languages keep their translations; new keys are
appended with the English text and listed so translators can find them. Strings with interpolation
(e.g. "\\(count) left") aren't extracted yet and stay in English.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources" / "Dockside"
LOCALES = ROOT / "Resources" / "Localization"

STRING = r'"((?:[^"\\\n]|\\.)*)"'
PATTERNS = [
    # SwiftUI initializers whose first argument is a LocalizedStringKey literal.
    re.compile(r'\b(?:Text|Button|Label|Toggle|Picker|Section|TextField|SecureField|Stepper|Menu|DatePicker|'
               r'DisclosureGroup)\(\s*' + STRING),
    re.compile(r'\.help\(\s*' + STRING),
    re.compile(r'String\(localized:\s*' + STRING),
    re.compile(r'PopoverHeader\(title:\s*' + STRING),
    re.compile(r'prompt:\s*Text\(\s*' + STRING),
]
# Ternaries of two UI phrases, e.g. visible ? "Hide Dockside" : "Show Dockside".
TERNARY = re.compile(r'\?\s*"([A-Z][^"\\.]*)"\s*:\s*"([A-Z][^"\\.]*)"')


# Enums whose raw values are shown in the UI through String(localized: String.LocalizationValue(rawValue)).
RAW_VALUE_ENUMS = ["WidgetCategory"]


def collect():
    keys = set()
    models = (SOURCES / "Models.swift").read_text()
    for name in RAW_VALUE_ENUMS:
        block = re.search(r"enum " + name + r"\b.*?\n}", models, re.S)
        if block:
            keys.update(re.findall(r'case \w+ = ' + STRING, block.group(0)))
    for path in sorted(SOURCES.rglob("*.swift")):
        text = path.read_text()
        for pat in PATTERNS:
            for m in pat.finditer(text):
                k = m.group(1)
                if k and "\\(" not in k:
                    keys.add(k)
        for m in TERNARY.finditer(text):
            keys.update(k for k in m.groups() if "\\(" not in k)
    return sorted(keys)


def read_strings(path):
    entries = {}
    if path.exists():
        for m in re.finditer(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', path.read_text(), re.M):
            entries[m.group(1)] = m.group(2)
    return entries


def write_strings(path, entries, keys, header):
    lines = [f"/* {header} */", ""]
    for k in keys:
        lines.append(f'"{k}" = "{entries.get(k, k)}";')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    check = "--check" in sys.argv
    keys = collect()
    write_strings(LOCALES / "en.lproj" / "Localizable.strings", {}, keys,
                  "English — generated by Scripts/extract-strings.py. Edit the Swift source, not this file.")
    missing_any = False
    for lproj in sorted(LOCALES.glob("*.lproj")):
        lang = lproj.stem
        if lang == "en":
            continue
        path = lproj / "Localizable.strings"
        entries = read_strings(path)
        missing = [k for k in keys if k not in entries]
        write_strings(path, entries, keys, f"{lang} — keep keys in sync with Scripts/extract-strings.py")
        if missing:
            missing_any = True
            print(f"{lang}: {len(missing)} untranslated (left in English):")
            for k in missing:
                print(f"   {k}")
        else:
            print(f"{lang}: complete ({len(keys)} strings)")
    print(f"en: {len(keys)} strings")
    if check and missing_any:
        sys.exit(1)


if __name__ == "__main__":
    main()
